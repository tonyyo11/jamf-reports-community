    /// The finished document around `mainBody`. Its charts are HTML and CSS, so the page
    /// loads no library.
    func buildDocument(
        outputURL: URL,
        mainBody: String,
        inputs: Inputs,
        profile: String,
        glance: Glance?
    ) -> String {
        let orgName = config.branding?.resolvedOrgName ?? ""
        let title = orgName.isEmpty ? "Jamf Reports" : orgName
        let titleEscaped = HtmlSectionFormatters.escapeHTML(title)
        let accentColor = (config.branding ?? BrandingConfig()).sanitizedAccentColor
        let verifyFilename = HtmlSectionFormatters.escapeHTML(outputURL.lastPathComponent)
        let placeholder = HTMLReportSHA256Placeholder
        let controls = !expandAll && mainBody.contains("<details")
        return """
        <!DOCTYPE html>
        <html lang="en" data-theme="light">
        <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <meta name="report-sha256" content="\(placeholder)">
        <title>\(titleEscaped) — Jamf Instance Report</title>
        \(buildCSS(accentColor: accentColor))
        </head>
        <body>
        <a class="skip-link" href="#main-content">Skip to main content</a>
        \(buildHeader(
            title: titleEscaped, facts: headerFacts(inputs, profile: profile),
            controls: controls))
        <main id="main-content">
        \(mainBody)
        </main>
        <footer>
          <p>Generated by Jamf Reports &middot;
            <a href="https://github.com/tonyyo11/jamf-reports-community"
            >tonyyo11/jamf-reports-community</a></p>
          <p class="verify-footer" style="margin-top:8px;font-size:11px;opacity:0.7">
            Source fingerprint: <code>\(placeholder)</code>
            &middot; verify with <code>shasum -a 256 \(verifyFilename)</code>
            (see <code>report-sha256</code> meta tag; replace the hash field with 64 zeros
            to reproduce)
          </p>
        </footer>
        \(buildScript())
        </body>
        </html>
        """
    }

    // MARK: Header

    /// The facts under the title, each only when the app has the value: profile, when the
    /// data was collected, the jamf-cli version, how many Macs, the template and the
    /// reporting week. A fact the app lacks is left out, never printed as a dash.
    func headerFacts(_ inputs: Inputs, profile: String) -> [(label: String, value: String)] {
        var facts: [(label: String, value: String)] = []
        if !profile.isEmpty { facts.append(("Profile", profile)) }
        let snapshotDates = inputs.sources.filter { $0.kind != "snapshots/summaries" }
            .compactMap(\.date)
        if let collected = snapshotDates.max() {
            facts.append(("Data collected", Self.mediumDateTime(collected)))
        }
        let recorded = inputs.summaries.last?.provenance?.jamfCLIVersion
        if let version = (jamfCLIVersion ?? recorded).flatMap(Self.versionNumber(in:)) {
            facts.append(("jamf-cli", version))
        }
        let macs = [inputs.computers.count, inputs.totalDevices,
                    inputs.summaries.last?.totalDevices ?? 0].first { $0 > 0 }
        if let macs { facts.append(("Macs", "\(macs)")) }
        if let templateName, !templateName.isEmpty { facts.append(("Template", templateName)) }
        if let current = inputs.summaries.last {
            let prior = FleetReportEmitter.priorSummary(inputs.summaries, lookbackDays: 7)
            facts.append(("Reporting week", prior.map { "\($0.date) to \(current.date)" }
                ?? "ending \(current.date)"))
        }
        return facts
    }

    /// The version number in `text` ("jamf-cli version 1.31.1 (abc)" gives "1.31.1"); the
    /// trimmed text itself when it holds no number, nil when it is blank.
    static func versionNumber(in text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        let pattern = #"\d+(?:\.\d+)+(?:[-+][A-Za-z0-9.]+)?"#
        if let range = trimmed.range(of: pattern, options: .regularExpression) {
            return String(trimmed[range])
        }
        return trimmed
    }

    private static func mediumDateTime(_ date: Date) -> String {
        let fmt = DateFormatter()
        fmt.dateStyle = .medium
        fmt.timeStyle = .short
        return fmt.string(from: date)
    }

    private func buildHeader(
        title: String, facts: [(label: String, value: String)], controls: Bool
    ) -> String {
        let f = HtmlSectionFormatters.self
        let factHTML = facts.map {
            "<span class=\"fact\">\(f.escapeHTML($0.label)): <strong>\(f.escapeHTML($0.value))"
                + "</strong></span>"
        }.joined(separator: "\n      ")
        let buttons = controls ? """
              <div class="controls" role="group" aria-label="Section controls">
                <button type="button" class="ctl" data-action="expand">Expand all</button>
                <button type="button" class="ctl" data-action="collapse">Collapse all</button>
              </div>
        """ : ""
        return """
        <header>
          <div class="header-content">
            <div>
              <h1>\(title)</h1>
              <p class="subtitle">Jamf Instance Report · \(f.escapeHTML(formattedNow()))</p>
              <p class="header-facts">
              \(factHTML)
              </p>
            </div>
            <div class="header-actions">
        \(buttons)
              <button class="theme-toggle" onclick="toggleTheme()" aria-label="Toggle theme"
                aria-pressed="false">&#9728; / &#9790;</button>
            </div>
          </div>
        </header>
        """
    }

