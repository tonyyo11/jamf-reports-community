    func buildScript() -> String {
        """
        <script>
        (function() {
          // Restore persisted theme preference; default is light.
          const saved = localStorage.getItem('jr-theme');
          if (saved === 'dark') {
            document.documentElement.setAttribute('data-theme', 'dark');
          }
        })();
        function toggleTheme() {
          const html = document.documentElement;
          const next = html.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
          html.setAttribute('data-theme', next);
          localStorage.setItem('jr-theme', next);
          const btn = document.querySelector('.theme-toggle');
          if (btn) btn.setAttribute('aria-pressed', next === 'dark' ? 'true' : 'false');
        }
        // Expand all / Collapse all.
        document.addEventListener('click', function(e) {
          var ctl = e.target.closest('[data-action]');
          if (!ctl) { return; }
          var open = ctl.getAttribute('data-action') === 'expand';
          document.querySelectorAll('details').forEach(function(d) { d.open = open; });
        });
        // A link to something inside a closed group opens the groups around it first.
        document.addEventListener('click', function(e) {
          var link = e.target.closest('a[href^="#"]');
          if (!link) { return; }
          jrReveal(decodeURIComponent(link.getAttribute('href').slice(1)));
        });
        function jrReveal(id) {
          var target = document.getElementById(id);
          if (!target) { return; }
          if (target.tagName === 'DETAILS') { target.open = true; }
          for (var n = target.parentElement; n; n = n.parentElement) {
            if (n.tagName === 'DETAILS') { n.open = true; }
          }
        }
        window.addEventListener('load', function() {
          if (location.hash.length > 1) {
            jrReveal(decodeURIComponent(location.hash.slice(1)));
          }
        });
        // Printing shows everything: open every group, then put back what was closed.
        var jrOpenedForPrint = [];
        window.addEventListener('beforeprint', function() {
          jrOpenedForPrint = [];
          document.querySelectorAll('details:not([open])').forEach(function(d) {
            d.open = true;
            jrOpenedForPrint.push(d);
          });
        });
        window.addEventListener('afterprint', function() {
          jrOpenedForPrint.forEach(function(d) { d.open = false; });
          jrOpenedForPrint = [];
        });
        // Cleanup Analysis tab navigation.
        // Buttons have class="cleanup-tab" and data-target="cpane-<id>".
        // Panes have id="cpane-<id>" and class="cleanup-pane [active]".
        document.addEventListener('click', function(e) {
          var btn = e.target.closest('.cleanup-tab');
          if (!btn) return;
          var container = btn.closest('.cleanup-tabs');
          if (!container) return;
          // Deactivate all sibling tabs.
          container.querySelectorAll('.cleanup-tab').forEach(function(t) {
            t.classList.remove('active');
            t.setAttribute('aria-selected', 'false');
            t.setAttribute('tabindex', '-1');
          });
          // Activate the clicked tab.
          btn.classList.add('active');
          btn.setAttribute('aria-selected', 'true');
          btn.setAttribute('tabindex', '0');
          // Deactivate all panes in the same block, then activate the target.
          var block = btn.closest('.block');
          if (block) {
            block.querySelectorAll('.cleanup-pane').forEach(function(p) {
              p.classList.remove('active');
            });
            var target = document.getElementById(btn.getAttribute('data-target'));
            if (target) target.classList.add('active');
          }
        });
        </script>
        """
    }
